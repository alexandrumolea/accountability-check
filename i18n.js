const params = new URLSearchParams(location.search);
const saved = (() => { try { return localStorage.getItem("acc5_lang"); } catch { return null; } })();
const pick = (l) => (LANGS.includes(l) ? l : null);
export const LANG = pick(params.get("lang")) || pick(saved) || "ro";
document.documentElement.lang = LANG;

const S = STRINGS[LANG];
export const t = (key, ...args) => (typeof S[key] === "function" ? S[key](...args) : S[key]);

export function setLang(l) {
  try { localStorage.setItem("acc5_lang", l); } catch {}
  const p = new URLSearchParams(location.search);
  p.set("lang", l);
  location.search = p.toString();
}
document.title = LANG === "en" ? "Accountability · 5 conditions" : "Accountability · 5 condiții";
